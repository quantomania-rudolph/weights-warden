"""Command-line front end:  ./h <command>.   Works for any agent that can run a shell command (Cursor, Claude Code, Codex, a human).
  ./h start [NAME] [--budget N]      new run (fresh ledger, budget of charged proposals) -> becomes the current run
  ./h tools                          the tools available in the configured mode, with their parameters
  ./h call TOOL ['{"json":"args"}']  run one tool on the current run (or --run NAME); prints JSON
  ./h status                         budget left + ledger integrity of the current run
  ./h finish [RUN]                   OVERSEER ONLY: the single held-out read for the run's best accepted edit
  ./h env                            effective configuration
  ./h docs                           regenerate agent/TOOLS.md and agent/tool_spec.json from the live tool specs"""
import os, sys, json, argparse
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.join(HERE, "agent_tools"))
import session as S, dispatch as D


def _fmt(spec):
    L = []
    for t in spec:
        props = t["parameters"].get("properties", {}); req = set(t["parameters"].get("required", []))
        args = ", ".join(f"{k}{'*' if k in req else ''}:{v.get('type', '?')}" for k, v in props.items()) or "no arguments"
        L.append(f"- `{t['name']}` ({args})\n  {t['description']}")
    return "\n".join(L)


def main(argv=None):
    ap = argparse.ArgumentParser(prog="h", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter); ap.add_argument("cmd", choices=["start", "tools", "call", "status", "finish", "env", "docs"])
    ap.add_argument("rest", nargs="*"); ap.add_argument("--budget", type=int); ap.add_argument("--run"); ap.add_argument("--json", action="store_true"); a = ap.parse_args(argv)
    out = None
    if a.cmd == "start": out = S.start_run(a.rest[0] if a.rest else None, a.budget)
    elif a.cmd == "tools":
        if a.json: out = S.tool_specs()
        else: print(f"mode: {os.environ.get('HARNESS_MODE', 'nav')}   (use `./h call TOOL '{{...}}'`)\n" + _fmt(S.tool_specs())); return 0
    elif a.cmd == "call":
        if not a.rest: raise SystemExit("usage: ./h call TOOL ['{\"json\": \"args\"}']")
        try: args = json.loads(a.rest[1]) if len(a.rest) > 1 else {}
        except json.JSONDecodeError as e: raise SystemExit(f"arguments must be a JSON object: {e}")
        out = S.call(a.rest[0], args, a.run)
    elif a.cmd == "status": out = S.call("status", {}, a.run)
    elif a.cmd == "finish": out = S.finish(a.rest[0] if a.rest else a.run)
    elif a.cmd == "env": out = {k: os.environ.get(k) for k in ("HARNESS_BACKEND", "HARNESS_MODE", "HARNESS_BUDGET", "HARNESS_RAW_VIEW", "HARNESS_CAVEATS", "HARNESS_PYTHONPATH", "HARNESS_RUNS")} | {"current_run": S.current_run(), "repo": S.REPO, "config_file": S.ENV_FILE}
    elif a.cmd == "docs":
        spec = {"llm": D.to_neutral(D.TOOLS_LLM), "nav": D.to_neutral(D.TOOLS)}; json.dump(spec, open(os.path.join(S.REPO, "agent", "tool_spec.json"), "w"), indent=1)
        open(os.path.join(S.REPO, "agent", "TOOLS.md"), "w").write("# Tool reference (generated by `./h docs`; `*` = required)\n\nSame tools through MCP and `./h call`. Which list you get is set by HARNESS_MODE in harness.env.\n\n## Transformer / MLP mode (HARNESS_MODE=llm)\n" + _fmt(spec["llm"]) + "\n\n## Nav2D mode (default)\n" + _fmt(spec["nav"]) + "\n")
        out = {"wrote": ["agent/TOOLS.md", "agent/tool_spec.json"]}
    print(json.dumps(out, default=str)); return 1 if isinstance(out, dict) and "error" in out else 0


if __name__ == "__main__": sys.exit(main())
